# ---- Embedding model ----
# Multilingual model: the corpus is English, but users may ask in French or
# Chinese; e5 maps all languages into the same vector space. Runs on CPU.
EMBEDDING_MODEL = "intfloat/multilingual-e5-base"
QUERY_PREFIX = "query: "            # e5 models require these prefixes
PASSAGE_PREFIX = "passage: "

# ---- Retrieval ----
CANDIDATES = 50                     # top-N from dense and from BM25 before fusion

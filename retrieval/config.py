"""Central configuration for the retrieval layer.

All tunable parameters live here so experiments only need to change this file.
"""
from pathlib import Path

# ---- Paths ----
ROOT = Path(__file__).resolve().parent.parent  # project root
CORPUS_PATH = ROOT / "data" / "corpus.jsonl"
TESTS_PATH = ROOT / "tests" / "tests.jsonl"
INDEX_DIR = ROOT / "index"          # generated by build_index.py, not committed
RESULTS_DIR = ROOT / "results"

# ---- Chunking (sizes in words) ----
CHUNK_SIZES = [100, 200, 400]       # compared in eval_retrieval.py
